// The sample: getrevlio.com (the author's own domain), read live. Lists its unexpired certificates from Certificate
// Transparency (CertSpotter), reads what each host serves on port 443, and writes the frozen sample for the app
// (public/samples/getrevlio.json) and the templates' values (docs/getrevlio.json, templates/_shared/example.ts).
// Run: node --experimental-strip-types scripts/sample.ts [domain] [YYYY-MM-DD]
import { writeFileSync } from "node:fs";
import { fromCertSpotter, hostnames, judgeAll, toValues } from "../templates/_shared/certs.ts";
import { servedAll } from "../src/lib/served.ts";

const domain = process.argv[2] ?? "getrevlio.com";
const date = process.argv[3] ?? new Date().toISOString().slice(0, 10);
const raw: unknown[] = [];
for (let after = ""; ; ) {
  const res = await fetch(`https://api.certspotter.com/v1/issuances?domain=${domain}&include_subdomains=true&expand=dns_names&expand=issuer${after ? `&after=${after}` : ""}`);
  if (!res.ok) throw new Error(`CertSpotter answered ${res.status}`);
  const page = (await res.json()) as Array<{ id: string }>;
  if (!page.length) break;
  raw.push(...page);
  after = page[page.length - 1].id;
}
const certs = fromCertSpotter(raw);
const served = await servedAll(hostnames(certs, domain).filter((h) => !h.startsWith("*.")));
writeFileSync(new URL("../public/samples/getrevlio.json", import.meta.url), JSON.stringify({ domains: [domain], date, certspotter: raw, served }, null, 1) + "\n");

const hosts = judgeAll([domain], certs, date, served);
const json = JSON.stringify(toValues(hosts, { domains: [domain], date, owner: "Rohit", team: "getrevlio.com" }), null, 2);
writeFileSync(new URL("../docs/getrevlio.json", import.meta.url), `${json}\n`);
writeFileSync(new URL("../templates/_shared/example.ts", import.meta.url), `// The sample: ${domain} (the author's own domain), read live on ${date}. Generated by scripts/sample.ts.\nconst example = ${json};\n\nexport default example;\n`);
console.log(date, certs.length, "certificates,", hosts.length, "hosts:", hosts.map((h) => `${h.host}=${h.state}`).join(" "));
